"""Build js/bart-shapes-data.js from BART's GTFS feed (exact track geometry + line colors).

Run again whenever BART updates its feed:
    python3 scripts/build_bart_shapes.py
"""
import csv
import io
import json
import urllib.request
import zipfile

GTFS_URL = "https://www.bart.gov/dev/schedules/google_transit.zip"
OUTPUT = "js/bart-shapes-data.js"
TOLERANCE_DEG = 0.00003  # ~3 m, drops points that don't change the line's shape


def read_csv(feed, name):
    with feed.open(name) as f:
        return list(csv.DictReader(io.TextIOWrapper(f, "utf-8-sig")))


def simplify(points, tolerance):
    """Ramer-Douglas-Peucker line simplification."""
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    length_sq = dx * dx + dy * dy
    max_dist, index = 0, 0
    for i in range(1, len(points) - 1):
        px, py = points[i]
        if length_sq == 0:
            dist = ((px - x1) ** 2 + (py - y1) ** 2) ** 0.5
        else:
            t = max(0, min(1, ((px - x1) * dx + (py - y1) * dy) / length_sq))
            dist = ((px - x1 - t * dx) ** 2 + (py - y1 - t * dy) ** 2) ** 0.5
        if dist > max_dist:
            max_dist, index = dist, i
    if max_dist <= tolerance:
        return [points[0], points[-1]]
    return simplify(points[: index + 1], tolerance)[:-1] + simplify(points[index:], tolerance)


def main():
    # bart.gov rejects Python's default user agent
    request = urllib.request.Request(GTFS_URL, headers={"User-Agent": "bike-transit-app"})
    with urllib.request.urlopen(request) as response:
        feed = zipfile.ZipFile(io.BytesIO(response.read()))

    colors = {r["route_id"]: "#" + r["route_color"] for r in read_csv(feed, "routes.txt")}
    shape_routes = {}
    for trip in read_csv(feed, "trips.txt"):
        if trip["shape_id"]:
            shape_routes.setdefault(trip["shape_id"], trip["route_id"])

    points = {}
    for row in read_csv(feed, "shapes.txt"):
        if row["shape_id"] in shape_routes:
            points.setdefault(row["shape_id"], []).append(
                (int(row["shape_pt_sequence"]), float(row["shape_pt_lon"]), float(row["shape_pt_lat"]))
            )

    shapes = []
    for shape_id, pts in sorted(points.items()):
        pts.sort()
        line = simplify([(lon, lat) for _, lon, lat in pts], TOLERANCE_DEG)
        shapes.append({
            "id": shape_id,
            "route": shape_routes[shape_id],  # matches the "ROUTE n" in BART API trip legs
            "color": colors.get(shape_routes[shape_id], "#666666"),
            "coords": [[round(lon, 5), round(lat, 5)] for lon, lat in line],
        })

    with open(OUTPUT, "w") as f:
        f.write("// Generated by scripts/build_bart_shapes.py from BART's GTFS feed. Don't edit by hand.\n")
        f.write("// Each shape is one BART line's track, as [lng, lat] points in travel order.\n")
        f.write("const BART_SHAPES = " + json.dumps(shapes, separators=(",", ":")) + ";\n")
    print("Wrote %d shapes, %d points to %s" % (len(shapes), sum(len(s["coords"]) for s in shapes), OUTPUT))


if __name__ == "__main__":
    main()
